// ---------------------------------------------------------------- 本地存储

/**
 * 消息预设的 localStorage 键（`core/websocket.svelte.ts` 读写）。
 * 只有预设落盘、且由用户点「保存到本地」触发；连接与定时任务一律不持久化。
 */
export const PRESET_STORAGE_KEY = 'websocket:presets';

// ---------------------------------------------------------------- 定时任务的默认间隔

/** 新建定时发送任务时的默认间隔（秒） */
export const DEFAULT_SCHEDULED_INTERVAL = 5;

/** 连接栏那个「新建连接自带定时任务」模板的默认间隔（秒），取保守值当保活用 */
export const DEFAULT_TEMPLATE_INTERVAL = 30;

// ---------------------------------------------------------------- 连接

/** 建连超时：地址不可达时浏览器自身超时可能拖很久，主动兜底 */
export const CONNECT_TIMEOUT_MS = 10_000;

// ---------------------------------------------------------------- 日志的上限

/** 日志软上限，超了丢最早的 */
export const LOG_LIMIT = 5000;

/** 触顶时多丢一些，免得每来一条都要搬一次数组 */
export const LOG_TRIM_STEP = 500;

/** 日志的渲染窗口：不设上限会把整页撑到几万 px，这里一次只渲染最近这么多条 */
export const RENDER_STEP = 300;
